-- =============================================================================
-- РЕШЕНИЕ ПО ENUM: VARCHAR + CHECK вместо CREATE TYPE ... AS ENUM
-- Причина: Hibernate @Enumerated(EnumType.STRING) пишет чистую строку.
-- PostgreSQL ENUM требовал бы кастомный UserType или @Type аннотацию.
-- VARCHAR + CHECK: работает с Hibernate из коробки, легко расширяется.
-- =============================================================================

-- =============================================================================
-- users
-- Entity: com.tradingbot.domain.model.User
-- =============================================================================
CREATE TABLE users (
                       id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       chat_id     BIGINT       NOT NULL,
                       username    VARCHAR(255),
                       tier        VARCHAR(16)  NOT NULL DEFAULT 'FREE'
                           CONSTRAINT chk_users_tier CHECK (tier IN ('FREE','PRO','VIP')),
                       active      BOOLEAN      NOT NULL DEFAULT TRUE,
                       created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       CONSTRAINT uq_users_chat_id UNIQUE (chat_id)
);

CREATE INDEX idx_users_active ON users (active) WHERE active = TRUE;


-- =============================================================================
-- orders
-- Entity: com.tradingbot.domain.model.OrderEntity
-- =============================================================================
CREATE TABLE orders (
                        id                   BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        client_order_id      VARCHAR(128)   NOT NULL,
                        exchange_order_id    VARCHAR(128),
                        user_id              BIGINT         NOT NULL,
                        strategy_id          VARCHAR(128)   NOT NULL,
                        symbol               VARCHAR(32)    NOT NULL,
                        side                 VARCHAR(8)     NOT NULL
                            CONSTRAINT chk_orders_side CHECK (side IN ('BUY','SELL')),
                        type                 VARCHAR(16)    NOT NULL
                            CONSTRAINT chk_orders_type CHECK (type IN ('MARKET','LIMIT','STOP_LOSS','TAKE_PROFIT')),
                        quantity             NUMERIC(28,8)  NOT NULL,
                        price                NUMERIC(28,8)  NOT NULL,
                        stop_loss            NUMERIC(28,8),
                        take_profit          NUMERIC(28,8),
                        status               VARCHAR(32)    NOT NULL DEFAULT 'NEW'
                            CONSTRAINT chk_orders_status CHECK (
                                status IN ('NEW','ACCEPTED','APPROVED','PENDING_EXECUTION',
                                           'EXECUTING','FILLED','REJECTED','ERROR')),
                        execution_owner      VARCHAR(255),
                        execution_expires_at TIMESTAMPTZ,
                        version              BIGINT         NOT NULL DEFAULT 0,
                        risk_state_version   BIGINT         NOT NULL DEFAULT 0,
                        created_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
                        updated_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
                        CONSTRAINT fk_orders_user        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
                        CONSTRAINT uq_orders_client_order_id UNIQUE (client_order_id)
);

CREATE INDEX idx_orders_status          ON orders (status);
CREATE INDEX idx_orders_user_id         ON orders (user_id);
CREATE INDEX idx_orders_strategy_status ON orders (strategy_id, status);
CREATE INDEX idx_orders_executing_lock  ON orders (execution_owner, execution_expires_at)
    WHERE status = 'EXECUTING';
CREATE INDEX idx_orders_exchange_id     ON orders (exchange_order_id)
    WHERE exchange_order_id IS NOT NULL;


-- =============================================================================
-- trades
-- Entity: com.tradingbot.infrastructure.persistence.entity.TradeEntity
-- =============================================================================
CREATE TABLE trades (
                        id                BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        order_id          BIGINT         NOT NULL,
                        client_order_id   VARCHAR(128)   NOT NULL,
                        user_id           BIGINT         NOT NULL,
                        strategy_id       VARCHAR(128)   NOT NULL,
                        symbol            VARCHAR(32)    NOT NULL,
                        side              VARCHAR(8)     NOT NULL
                            CONSTRAINT chk_trades_side CHECK (side IN ('BUY','SELL')),
                        quantity          NUMERIC(28,8)  NOT NULL,
                        price             NUMERIC(28,8)  NOT NULL,
                        net_quantity      NUMERIC(28,8),
                        avg_entry_price   NUMERIC(28,8),
                        realized_pnl      NUMERIC(28,8),
                        commission        NUMERIC(28,8),
                        commission_asset  VARCHAR(16),
                        exchange_trade_id VARCHAR(128),
    -- GENERATED ALWAYS AS IDENTITY: Hibernate не пишет это поле (insertable=false)
                        sequence_id       BIGINT         GENERATED ALWAYS AS IDENTITY,
                        executed_at       TIMESTAMPTZ,
                        created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
                        CONSTRAINT fk_trades_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE RESTRICT,
                        CONSTRAINT fk_trades_user  FOREIGN KEY (user_id)  REFERENCES users (id)  ON DELETE RESTRICT,
                        CONSTRAINT uq_trades_exchange_trade_id UNIQUE (exchange_trade_id)
);

CREATE INDEX idx_trades_order_id        ON trades (order_id);
CREATE INDEX idx_trades_client_order_id ON trades (client_order_id);
CREATE INDEX idx_trades_symbol_executed ON trades (symbol, executed_at DESC);
CREATE INDEX idx_trades_user_strategy   ON trades (user_id, strategy_id, executed_at DESC);


-- =============================================================================
-- positions
-- Entity: com.tradingbot.domain.model.PositionEntity
-- ВАЖНО: Entity поле quantity → колонка net_quantity
--        Entity поле entryPrice → колонка avg_entry_price
-- =============================================================================
CREATE TABLE positions (
                           id               BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           symbol           VARCHAR(32)    NOT NULL,
                           strategy_id      VARCHAR(128)   NOT NULL,
                           user_id          BIGINT         NOT NULL,
                           net_quantity     NUMERIC(28,8)  NOT NULL DEFAULT 0,
                           avg_entry_price  NUMERIC(28,8),
                           realized_pnl     NUMERIC(28,8)  NOT NULL DEFAULT 0,
                           stop_loss        NUMERIC(28,8),
                           take_profit      NUMERIC(28,8),
                           status           VARCHAR(16)    NOT NULL DEFAULT 'OPEN'
                               CONSTRAINT chk_positions_status CHECK (status IN ('OPEN','CLOSING','CLOSED')),
                           last_trade_id    BIGINT,
                           close_request_id UUID,
                           version          BIGINT         NOT NULL DEFAULT 0,
                           created_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
                           updated_at       TIMESTAMPTZ    NOT NULL DEFAULT now(),
                           CONSTRAINT fk_positions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
                           CONSTRAINT uq_positions_open UNIQUE (symbol, strategy_id, user_id)
);

CREATE INDEX idx_positions_user_strategy ON positions (user_id, strategy_id);
CREATE INDEX idx_positions_symbol_status ON positions (symbol, status);
CREATE INDEX idx_positions_close_req     ON positions (close_request_id)
    WHERE close_request_id IS NOT NULL;


-- =============================================================================
-- signals
-- Entity: com.tradingbot.domain.event.SignalEntity
-- =============================================================================
CREATE TABLE signals (
                         id           BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         symbol       VARCHAR(32)    NOT NULL,
                         type         VARCHAR(8)     NOT NULL
                             CONSTRAINT chk_signals_type CHECK (type IN ('BUY','SELL','HOLD')),
                         strategy_id  VARCHAR(128)   NOT NULL,
                         user_id      BIGINT,
                         price        NUMERIC(28,8),
                         take_profit1 NUMERIC(28,8),
