                         stop_loss    NUMERIC(28,8),
                         created_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
                         timestamp    TIMESTAMPTZ,
                         CONSTRAINT fk_signals_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_signals_strategy_created ON signals (strategy_id, created_at DESC);
CREATE INDEX idx_signals_symbol_created   ON signals (symbol, created_at DESC);


-- =============================================================================
-- outbox_events
-- Entity: com.tradingbot.infrastructure.persistence.entity.OutboxEventEntity
-- =============================================================================
CREATE TABLE outbox_events (
                               event_id        UUID           PRIMARY KEY DEFAULT gen_random_uuid(),
                               client_order_id VARCHAR(128)   NOT NULL,
                               type            VARCHAR(128)   NOT NULL,
                               payload         JSONB          NOT NULL,
                               status          VARCHAR(16)    NOT NULL DEFAULT 'PENDING'
                                   CONSTRAINT chk_outbox_status CHECK (status IN ('PENDING','SENT','FAILED')),
                               retry_count     INT            NOT NULL DEFAULT 0,
                               max_retries     INT            NOT NULL DEFAULT 5,
                               error_message   TEXT,
                               created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
                               processed_at    TIMESTAMPTZ,
                               next_retry_at   TIMESTAMPTZ    NOT NULL DEFAULT now()
);

CREATE INDEX idx_outbox_pending         ON outbox_events (next_retry_at) WHERE status = 'PENDING';
CREATE INDEX idx_outbox_client_order_id ON outbox_events (client_order_id);
CREATE INDEX idx_outbox_failed          ON outbox_events (created_at)    WHERE status = 'FAILED';


