package com.tradingbot.domain.position;

/**
 * Статус жизненного цикла торговой позиции.
 * <p>
 * Определяет текущее состояние позиции в рамках её открытия, удержания и закрытия.
 */
public enum PositionStatus {

    /**
     * Позиция создана, но ещё не открыта (нет фактического объёма).
     */
    NEW,

    /**
     * Позиция активна и имеет ненулевой объём.
     */
    OPEN,

    /**
     * Позиция находится в процессе закрытия (есть инициированное закрытие).
     */
    CLOSING,

    /**
     * Позиция полностью закрыта (netQuantity == 0).
     */
    CLOSED
}