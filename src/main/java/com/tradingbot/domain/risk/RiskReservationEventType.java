package com.tradingbot.domain.risk;

/**
 * Типы событий резервирования капитала в риск-системе.
 * <p>
 * Используются для управления жизненным циклом зарезервированных средств:
 * резервирование под ордер и освобождение при отмене или завершении.
 */
public enum RiskReservationEventType {

    /**
     * Резервирование капитала под торговый ордер.
     */
    RESERVE,

    /**
     * Освобождение ранее зарезервированного капитала.
     */
    RELEASE
}