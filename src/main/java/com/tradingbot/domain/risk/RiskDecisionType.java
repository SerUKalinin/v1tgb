package com.tradingbot.domain.risk;

/**
 * Типы решений риск-менеджмента.
 * <p>
 * Определяют итоговый статус обработки торгового сигнала
 * после прохождения всех риск-правил и проверок.
 */
public enum RiskDecisionType {

    /**
     * Сигнал одобрен к дальнейшему исполнению.
     */
    APPROVED,

    /**
     * Сигнал отклонён на уровне риск-менеджмента.
     */
    REJECTED,

    /**
     * Обработка сигнала временно приостановлена (risk halt).
     */
    HALTED,

    /**
     * Сигнал признан невозможным к исполнению (например, недостаток ликвидности или ограничение биржи).
     */
    NOT_FEASIBLE
}