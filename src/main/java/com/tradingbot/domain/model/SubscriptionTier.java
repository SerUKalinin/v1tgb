package com.tradingbot.domain.model;

/**
 * Уровень подписки пользователя или стратегии.
 * <p>
 * Используется для определения доступных возможностей системы,
 * лимитов, приоритетов обработки и функциональных ограничений.
 */
public enum SubscriptionTier {

    /**
     * Бесплатный уровень доступа с базовыми ограничениями.
     */
    FREE,

    /**
     * Расширенный уровень доступа для активных пользователей.
     */
    PRO,

    /**
     * Максимальный уровень доступа с приоритетным исполнением
     * и расширенными лимитами системы.
     */
    VIP
}