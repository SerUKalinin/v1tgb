package com.tradingbot.domain.exchange;

/**
 * Порт проверки возможности исполнения операции на бирже.
 * <p>
 * Используется для валидации того, может ли биржа принять и исполнить
 * торговый запрос с учётом текущих ограничений (баланс, лимиты,
 * правила биржи, ликвидность и т.д.).
 */
public interface ExchangeFeasibilityPort {

    /**
     * Выполняет проверку возможности исполнения торгового запроса.
     *
     * @param request запрос с параметрами сделки, которые необходимо проверить
     * @return результат проверки, содержащий информацию о допустимости исполнения
     */
    FeasibilityResult check(FeasibilityRequest request);
}