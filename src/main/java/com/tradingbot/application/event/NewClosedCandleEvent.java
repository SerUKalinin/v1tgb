package com.tradingbot.application.event;

import java.math.BigDecimal;
import java.time.Instant;

/**
 * Событие закрытой свечи (Candle Close Event).
 *
 * <p>Представляет собой событие, которое возникает
 * в момент фактического закрытия рыночной свечи
 * и передаётся в стратегический слой для генерации
 * торговых сигналов.</p>
 *
 * <p>Событие содержит одновременно openTime и closeTime,
 * поскольку openTime является идентификатором конкретной свечи,
 * а closeTime описывает момент её закрытия.</p>
 *
 * <p>Инвариант: все рыночные значения соответствуют
 * финальному состоянию свечи на момент закрытия.</p>
 */
public record NewClosedCandleEvent(

        /**
         * Торговый символ.
         */
        String symbol,

        /**
         * Уникальное время открытия данной свечи.
         *
         * <p>Используется как идентификатор конкретной
         * свечи внутри одного symbol + interval.</p>
         */
        Instant openTime,

        /**
         * Цена открытия свечи.
         */
        BigDecimal open,

        /**
         * Максимальная цена за период свечи.
         */
        BigDecimal high,

        /**
         * Минимальная цена за период свечи.
         */
        BigDecimal low,

        /**
         * Цена закрытия свечи.
         */
        BigDecimal close,

        /**
         * Объём торгов за свечу.
         */
        BigDecimal volume,

        /**
         * Время закрытия свечи.
         */
        Instant closeTime
) {
}