package com.tradingbot.application.event;

import java.time.Instant;

/**
 * Контракт хранилища для фиксации уже обработанных свечей.
 * <p>
 * Используется для обеспечения идемпотентности обработки рыночных данных
 * и предотвращения повторной генерации событий по одной и той же свече.
 * <p>
 * Гарантирует, что каждая свеча будет обработана не более одного раза
 * в рамках жизненного цикла системы или реализации хранилища.
 */
public interface ProcessedCandleRepository {

    /**
     * Регистрирует свечу как обработанную.
     *
     * @param symbol торговый символ (например BTCUSDT)
     * @param openTime время открытия свечи
     * @return true, если свеча ранее не была обработана и успешно зарегистрирована,
     *         false если она уже присутствует в хранилище
     */
    boolean markAsProcessed(String symbol, Instant openTime);
}