package com.tradingbot.common.enums;

/**
 * Тип ордера.
 *
 * <p>Определяет способ исполнения заявки на рынке.</p>
 */
public enum OrderType {

    /**
     * Рыночный ордер — исполняется по текущей рыночной цене.
     */
    MARKET,

    /**
     * Лимитный ордер — исполняется по заданной цене или лучше.
     */
    LIMIT,

    /**
     * Stop-loss ордер — используется для ограничения убытков.
     */
    STOP_LOSS,

    /**
     * Take-profit ордер — фиксирует прибыль при достижении цели.
     */
    TAKE_PROFIT
}