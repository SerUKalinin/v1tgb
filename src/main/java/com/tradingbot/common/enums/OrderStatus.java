package com.tradingbot.common.enums;

/**
 * Статусы жизненного цикла ордера.
 *
 * <p>Описывает полный state machine ордера от создания до финального состояния.
 * Используется для контроля исполнения, идемпотентности и восстановления состояния.</p>
 */
public enum OrderStatus {

    /**
     * Ордер создан в системе, начальное состояние.
     */
    NEW,

    /**
     * Ордер прошёл валидацию риск-менеджмента.
     */
    VALIDATED,

    /**
     * Ордер ожидает асинхронного исполнения.
     */
    PENDING_EXECUTION,

    /**
     * Ордер находится в процессе исполнения (атомарный захват).
     */
    EXECUTING,

    /**
     * Ордер отправлен в обработку.
     */
    SENT,

    /**
     * Ордер отправлен в биржевой шлюз и ожидает подтверждения.
     */
    SENT_TO_EXCHANGE,

    /**
     * Ордер частично исполнен.
     */
    PARTIALLY_FILLED,

    /**
     * Ордер полностью исполнен.
     */
    FILLED,

    /**
     * Ордер отменён пользователем или биржей.
     */
    CANCELED,

    /**
     * Ордер отклонён системой риск-менеджмента или биржей.
     */
    REJECTED,

    /**
     * Неизвестный результат исполнения (timeout / неопределённое состояние).
     */
    UNKNOWN,

    /**
     * Ордер находится в процессе восстановления состояния.
     */
    RECOVERING,

    /**
     * Критическая ошибка обработки ордера.
     */
    ERROR
}