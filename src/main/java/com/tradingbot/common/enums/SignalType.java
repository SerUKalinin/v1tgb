package com.tradingbot.common.enums;

/**
 * Типы торговых сигналов.
 *
 * <p>Используются стратегическим движком для определения предполагаемого
 * действия на рынке.</p>
 */
public enum SignalType {

    /**
     * Сигнал на открытие или усиление длинной позиции.
     */
    BUY,

    /**
     * Сигнал на открытие или усиление короткой позиции.
     */
    SELL,

    /**
     * Отсутствие торгового действия (ожидание).
     */
    HOLD
}