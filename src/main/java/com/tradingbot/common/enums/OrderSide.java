package com.tradingbot.common.enums;

/**
 * Сторона торгового ордера.
 *
 * <p>Определяет направление сделки на рынке.</p>
 */
public enum OrderSide {

    /**
     * Покупка актива (long / открытие позиции вверх).
     */
    BUY,

    /**
     * Продажа актива (short / закрытие или открытие позиции вниз).
     */
    SELL
}